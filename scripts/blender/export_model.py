"""Writes a Blender mesh as a tiny ES module for js/render/artifact3d.js.

Output: { palette: [[r, g, b]], verts: [x, y, z, ...], tris: [a, b, c, paletteIndex, ...] }
Colours are the materials' viewport display colours, read as sRGB. Axes go from Blender
(z up, front = -y) to the game (y up, front = +z): (x, y, z) -> (x, z, -y).
extra: more fields for the module, e.g. a pivot point; points (3-tuples) are converted too.
"""
import os

import bpy


def fmt(v):
    s = f'{v:.4f}'.rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s


def to_game(p):
    x, y, z = p
    return (x, z, -y)


def export_model(ob, name, path, source, extra=None):
    dg = bpy.context.evaluated_depsgraph_get()
    me = ob.evaluated_get(dg).to_mesh()
    me.calc_loop_triangles()

    palette = [tuple(m.diffuse_color[:3]) for m in me.materials]
    verts = []
    for v in me.vertices:
        x, y, z = v.co
        verts += [x, z, -y]
    tris = []
    for t in me.loop_triangles:
        tris += [*t.vertices, t.material_index]

    lines = [
        f'// Generated by {source} — do not edit by hand.',
        f'// {len(me.vertices)} vertices, {len(me.loop_triangles)} triangles.',
        f'export const {name.upper()} = {{',
        f"  name: '{name}',",
        '  palette: [' + ', '.join('[' + ', '.join(fmt(c) for c in p) + ']' for p in palette) + '],',
    ]
    for key, value in (extra or {}).items():
        if isinstance(value, tuple) and len(value) == 3:
            value = '[' + ', '.join(fmt(c) for c in to_game(value)) + ']'
        lines.append(f'  {key}: {value},')
    lines.append('  verts: [')
    for i in range(0, len(verts), 12):
        lines.append('    ' + ', '.join(fmt(c) for c in verts[i:i + 12]) + ',')
    lines += ['  ],', '  tris: [']
    for i in range(0, len(tris), 16):
        lines.append('    ' + ', '.join(str(c) for c in tris[i:i + 16]) + ',')
    lines += ['  ],', '};', '']

    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    ob.evaluated_get(dg).to_mesh_clear()
    print(f'wrote {path}: {len(verts) // 3} verts, {len(tris) // 4} tris')
