// Writes sw.js: the service worker with the version from js/version.js and the list of
// every file the game needs offline. Run after adding/removing files or bumping VERSION:
//   node scripts/build-sw.mjs
// tests/pwa.test.js fails when sw.js is out of date.

import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

function walk(dir, keep) {
  const out = [];
  for (const name of readdirSync(join(root, dir)).sort()) {
    const rel = join(dir, name);
    if (statSync(join(root, rel)).isDirectory()) out.push(...walk(rel, keep));
    else if (keep(name)) out.push(rel.split(sep).join('/'));
  }
  return out;
}

export function collectAssets() {
  return [
    './',
    'index.html',
    'manifest.webmanifest',
    ...walk('css', (n) => n.endsWith('.css')),
    ...walk('js', (n) => n.endsWith('.js')),
    ...walk('assets/fonts', (n) => n.endsWith('.woff2')),
    ...walk('assets/icons', (n) => n.endsWith('.png')),
  ];
}

export function readVersion() {
  return /VERSION = '([^']+)'/.exec(readFileSync(join(root, 'js/version.js'), 'utf8'))[1];
}

export function renderSw(version = readVersion(), assets = collectAssets()) {
  return `// Generated by scripts/build-sw.mjs — do not edit by hand.
// Cache-first service worker: the whole game works offline after the first visit.

const VERSION = '${version}';
const CACHE = \`reliq-\${VERSION}\`;
const ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('reliq-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Only this game's own cache is searched: other apps on the same origin (e.g. a GitHub
// Pages user site) keep caches of their own.
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(caches.open(CACHE).then((cache) =>
    cache.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) cache.put(req, res.clone());
      return res;
    }).catch(() => (req.mode === 'navigate' ? cache.match('./') : Response.error())))));
});
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, 'sw.js'), renderSw());
  console.log(`sw.js written: version ${readVersion()}, ${collectAssets().length} files`);
}
